package usecase

import "testing"

func TestNormalizeAmounts(t *testing.T) {
	cases := map[string]string{
		// Голые числа остаются как есть: 20 ₽ — это 20 ₽.
		"кофе 20":             "кофе 20",
		"обед 350":            "обед 350",
		"такси 1 200":         "такси 1200",
		"ремонт 12 500 р":     "ремонт 12500 р",
		"аптека 99,90":        "аптека 99.90",
		"кофе 350, такси 500": "кофе 350, такси 500",
		// Тысячи цифрами.
		"такси 2к":          "такси 2000",
		"куртка 1.5к":       "куртка 1500",
		"куртка 4,5к":       "куртка 4500",
		"ноутбук 80 тыс":    "ноутбук 80000",
		"телефон 30 тысяч":  "телефон 30000",
		"отдал 2 косаря":    "отдал 2000",
		"кофе 350 к обеду":  "кофе 350 к обеду",
		"купил 3 штуки 300": "купил 3 штуки 300",
		// Сленг без цифр.
		"такси пятихатка":            "такси 500",
		"продукты пятера":            "продукты 5000",
		"обувь шестера":              "обувь 6000",
		"бензин двушка":              "бензин 2000",
		"ресторан касарь":            "ресторан 1000",
		"косарик на такси":           "1000 на такси",
		"кофе сотка":                 "кофе 100",
		"подарок полтыщи":            "подарок 500",
		"куртка полторы":             "куртка 1500",
		"полтора косаря на бензин":   "1500 на бензин",
		"полторы тысячи на продукты": "1500 на продукты",
		"кино трёшка":                "кино 3000",
		"такси штуку":                "такси 1000",
		"сотка и сотка":              "100 и 100",
		"четыре с половиной косаря":  "четыре с половиной косаря",
		"две сотки":                  "две сотки",
		// С цифрами сленг — не сумма: «двушка» тут квартира.
		"аренда двушки 40к": "аренда двушки 40000",
		// Похожие слова не задеты.
		"пятерочка 800":       "пятерочка 800",
		"продукты пятерочка":  "продукты пятерочка",
		"сотрудник косметика": "сотрудник косметика",
	}
	for in, want := range cases {
		if got := normalizeAmounts(in); got != want {
			t.Errorf("normalizeAmounts(%q) = %q, want %q", in, got, want)
		}
	}
}
